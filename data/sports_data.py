"""
data/sports_data.py — Comprehensive data backbone for the Sports Sponsorship Valuator.

Contains hardcoded property stats, brand profiles, historical deal comparables,
athlete data, and demographic profiles. All figures sourced from publicly available
sponsorship industry reports (Deloitte, Nielsen Sports, SportsPro Media, Forbes).

This module is the single source of truth for all static data in the project.
"""

from dataclasses import dataclass, field
from typing import Optional


# ── Data Classes ──────────────────────────────────────────────────────────────

@dataclass
class SportsProperty:
    """A sponsorable sports entity: team, league, event, or venue."""
    name: str
    sport: str
    league: str
    country: str
    annual_attendance: int           # stadium/venue attendance per year
    avg_matchday_attendance: int
    stadium_capacity: int
    avg_broadcast_viewers_m: float   # millions per game
    broadcast_frequency: int         # games broadcast per year
    social_followers_m: float        # total cross-platform followers (millions)
    instagram_followers_m: float
    twitter_followers_m: float
    youtube_subscribers_m: float
    avg_engagement_rate: float       # % of followers who engage per post
    domestic_fanbase_pct: float      # % of fans based in home country
    international_fanbase_pct: float
    primary_market: str
    brand_value_usd_m: float         # estimated brand/franchise value
    shirt_deal_current_brand: str
    shirt_deal_annual_value_usd_m: float
    stadium_name: str
    naming_rights_brand: Optional[str]


@dataclass
class BrandProfile:
    """A corporate brand seeking sponsorship."""
    name: str
    category: str                    # beer_alcohol, telecoms, automotive, etc.
    annual_revenue_usd_b: float      # billions
    global_marketing_budget_usd_m: float
    sponsorship_budget_usd_m: float
    target_age_18_24: float          # fraction of target demo (sums to 1.0)
    target_age_25_34: float
    target_age_35_44: float
    target_age_45_54: float
    target_age_55_plus: float
    target_gender_male: float        # fraction
    target_hhi_under_50k: float
    target_hhi_50_100k: float
    target_hhi_over_100k: float
    target_geographies: list         # primary markets
    brand_sentiment: float           # -1 to 1 public sentiment score
    existing_sports_properties: list


@dataclass
class SponsorshipDeal:
    """A historical or active sponsorship deal."""
    deal_id: str
    property_name: str
    brand_name: str
    deal_type: str                   # jersey, stadium_naming, title_sponsor, broadcast, athlete
    annual_value_usd_m: float
    year_signed: int
    deal_duration_years: int
    is_exclusive: bool
    sport: str
    league: str
    notes: str


@dataclass
class Athlete:
    """An individual athlete with endorsement value data."""
    name: str
    sport: str
    team: str
    nationality: str
    age: int
    instagram_followers_m: float
    twitter_followers_m: float
    tiktok_followers_m: float
    youtube_subscribers_m: float
    avg_engagement_rate: float       # %
    on_field_rating: float           # 0-10 performance rating
    global_recognition_score: float  # 0-10 name recognition globally
    controversiality_score: float    # 0-10 (higher = more controversial, risk)
    current_endorsement_deals: list
    primary_demographic_appeal: str  # which age/demo segment follows them most


