def get_property(name: str) -> Optional[SportsProperty]:
    """Look up a sports property by key."""
    return SPORTS_PROPERTIES.get(name)


def get_brand(name: str) -> Optional[BrandProfile]:
    """Look up a brand profile by key."""
    return BRAND_PROFILES.get(name)


def get_athlete(name: str) -> Optional[Athlete]:
    """Look up an athlete profile by key."""
    return ATHLETE_PROFILES.get(name)


def list_properties() -> list[str]:
    """Return all available property keys."""
    return list(SPORTS_PROPERTIES.keys())


def list_brands() -> list[str]:
    """Return all available brand keys."""
    return list(BRAND_PROFILES.keys())


def list_athletes() -> list[str]:
    """Return all available athlete keys."""
    return list(ATHLETE_PROFILES.keys())


def get_deals_for_property(property_name: str) -> list[SponsorshipDeal]:
    """Return all historical deals for a given property name."""
    normalized = property_name.lower()
    return [d for d in HISTORICAL_DEALS if normalized in d.property_name.lower()]


def get_deals_by_type(deal_type: str) -> list[SponsorshipDeal]:
    """Return all deals of a given type (jersey, stadium_naming, etc.)."""
    return [d for d in HISTORICAL_DEALS if d.deal_type == deal_type]
